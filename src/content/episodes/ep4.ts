/** The sparkwire threads on the broken top run from each Anchor to where the Unmaker stands (36, 28). */
function threadOff(ax: number, az: number): Blk[] {
  const out: Blk[] = [];
  for (let k = 2; k <= 9; k++) {
    const t = k / 10;
    out.push([Math.round(ax + (36 - ax) * t), 31, Math.round(az + (28 - az) * t), 'air']);
  }
  return out;
}

